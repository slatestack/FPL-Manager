# FPL Manager installer for Windows (PowerShell). Safe to re-run: keeps an existing .env.
$ErrorActionPreference = "Stop"
Set-Location (Join-Path $PSScriptRoot "..")

function Say($text) { Write-Host "`n$text" -ForegroundColor Cyan }
function NewKey([int]$bytes) {
    $b = New-Object byte[] $bytes
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b)
    return [Convert]::ToBase64String($b).Replace('+', '-').Replace('/', '_')
}

if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    Write-Host "Docker is not installed. Install Docker Desktop: https://www.docker.com/products/docker-desktop/"; exit 1
}
docker info *> $null
if ($LASTEXITCODE -ne 0) { Write-Host "Docker is installed but not running. Start Docker Desktop, wait for it, then run this again."; exit 1 }

if (-not (Test-Path .env)) {
    Say "Settings"
    $team = Read-Host "Your FPL team ID (the number in fantasy.premierleague.com/entry/<ID>/history)"
    if ($team -notmatch '^\d+$') { Write-Host "The team ID must be a number."; exit 1 }
    $odds = Read-Host "The Odds API key (optional, press Enter to skip)"
    $tg = Read-Host "Telegram bot token for alerts (optional, press Enter to skip)"
    $chat = ""
    if ($tg) { $chat = Read-Host "Your Telegram chat ID" }
    $secret = NewKey 32
    $api = (NewKey 24).TrimEnd('=')
    @"
FPL_TEAM_ID=$team
FPL_ODDS_API_KEY=$odds
FPL_TELEGRAM_BOT_TOKEN=$tg
FPL_TELEGRAM_CHAT_ID=$chat
# Generated by the installer. Keep this file private: the secret key decrypts your stored FPL login.
FPL_SECRET_KEY=$secret
FPL_API_TOKEN=$api
FPL_RAW_SNAPSHOT_RETENTION_DAYS=7
"@ | Set-Content -Path .env -Encoding ascii
    Write-Host "Saved settings to .env"
} else {
    Say "Using existing .env"
}

Say "Building and starting (the first build downloads ~1 GB and takes a few minutes)"
docker compose up -d --build
if ($LASTEXITCODE -ne 0) { exit 1 }

Write-Host -NoNewline "Waiting for the system to come up"
$ready = $false
for ($i = 0; $i -lt 90; $i++) {
    try { Invoke-WebRequest -UseBasicParsing http://127.0.0.1:8000/healthz -TimeoutSec 2 | Out-Null; $ready = $true; break }
    catch { Write-Host -NoNewline "."; Start-Sleep -Seconds 2 }
}
if (-not $ready) { Write-Host "`nThe API did not start. Check: docker compose logs api"; exit 1 }
Write-Host " ready."

Say "Sign in to FPL"
Write-Host "You'll get a normal FPL sign-in link. Sign in, then paste back the address you land on."
docker compose exec ingestion-worker python -m app auth login
$signedIn = ($LASTEXITCODE -eq 0)
if (-not $signedIn) { Write-Host "Not signed in yet. Run later: docker compose exec ingestion-worker python -m app auth login" }

if ($signedIn) {
    Say "Automatic execution"
    Write-Host "When on, planned transfers, lineup, captain and chips are submitted 15 minutes before each deadline,"
    Write-Host "after safety checks. Switch it off any time (dashboard or Telegram /killswitch)."
    $arm = Read-Host "Turn automatic execution on now? [y/N]"
    if ($arm -match '^(y|yes)$') { docker compose exec ingestion-worker python -m app config --auto-execute on }
    else { Write-Host "Left off. Plans will still be prepared and sent to you before every deadline." }
}

Say "Done"
Write-Host "Dashboard:     http://localhost:8000"
Write-Host "API token:     in .env (FPL_API_TOKEN), needed for the dashboard's on/off switch"
Write-Host "Kill switch:   docker compose exec ingestion-worker python -m app config --auto-execute off"
Write-Host "Keep Docker Desktop set to start when you sign in, and keep this PC awake around deadlines."
