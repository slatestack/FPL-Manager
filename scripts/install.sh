#!/usr/bin/env bash
# FPL Manager installer for macOS and Linux. Safe to re-run: keeps an existing .env.
set -euo pipefail
cd "$(dirname "$0")/.."

say() { printf '\n\033[1m%s\033[0m\n' "$*"; }
ask() { local prompt=$1 var; read -r -p "$prompt" var || true; printf '%s' "$var"; }
EXEC=(docker compose exec)
[ -t 0 ] || EXEC=(docker compose exec -T)

command -v docker >/dev/null 2>&1 || { echo "Docker is not installed. Install Docker Desktop: https://www.docker.com/products/docker-desktop/"; exit 1; }
docker info >/dev/null 2>&1 || { echo "Docker is installed but not running. Start Docker Desktop, wait for it to finish starting, then run this again."; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "Docker Compose v2 is required (it comes with Docker Desktop)."; exit 1; }

if [ ! -f .env ]; then
  say "Settings"
  TEAM_ID=$(ask "Your FPL team ID (the number in fantasy.premierleague.com/entry/<ID>/history): ")
  case "$TEAM_ID" in ''|*[!0-9]*) echo "The team ID must be a number."; exit 1;; esac
  ODDS_KEY=$(ask "The Odds API key (optional, press Enter to skip): ")
  echo
  echo "WhatsApp alerts (optional). To get a free key: add +34 644 66 32 62 to your phone contacts, then send it"
  echo "the WhatsApp message 'I allow callmebot to send me messages'. It replies with your API key."
  WA_PHONE=$(ask "Your WhatsApp number with country code, e.g. +19195551234 (press Enter to skip): ")
  WA_KEY=""
  [ -n "$WA_PHONE" ] && WA_KEY=$(ask "Your CallMeBot API key: ")
  SECRET_KEY=$(head -c 32 /dev/urandom | base64 | tr '+/' '-_' | tr -d '\n')
  API_TOKEN=$(head -c 24 /dev/urandom | base64 | tr '+/' '-_' | tr -d '=\n')
  umask 077
  cat > .env <<ENV
FPL_TEAM_ID=$TEAM_ID
FPL_ODDS_API_KEY=$ODDS_KEY
FPL_WHATSAPP_PHONE=$WA_PHONE
FPL_WHATSAPP_APIKEY=$WA_KEY
# Generated by the installer. Keep this file private: the secret key decrypts your stored FPL login.
FPL_SECRET_KEY=$SECRET_KEY
FPL_API_TOKEN=$API_TOKEN
FPL_RAW_SNAPSHOT_RETENTION_DAYS=7
ENV
  echo "Saved settings to .env (readable only by you)."
else
  say "Using existing .env"
fi

say "Building and starting (the first build downloads ~1 GB and takes a few minutes)"
docker compose up -d --build

printf 'Waiting for the system to come up'
for _ in $(seq 1 90); do
  if curl -fs http://127.0.0.1:8000/healthz >/dev/null 2>&1; then echo " ready."; break; fi
  printf '.'; sleep 2
done
curl -fs http://127.0.0.1:8000/healthz >/dev/null 2>&1 || { echo; echo "The API did not start. Check: docker compose logs api"; exit 1; }

if grep -qE '^FPL_WHATSAPP_APIKEY=.+' .env; then
  say "Sending a test WhatsApp message"
  "${EXEC[@]}" ingestion-worker python -m app notify-test || echo "Check the number and key in .env, then run: docker compose exec ingestion-worker python -m app notify-test"
fi

say "Sign in to FPL"
echo "You'll get a normal FPL sign-in link. Sign in, then paste back the address you land on."
if "${EXEC[@]}" ingestion-worker python -m app auth login; then
  SIGNED_IN=1
else
  SIGNED_IN=0
  echo "Not signed in yet. Run this later:  docker compose exec ingestion-worker python -m app auth login"
fi

if [ "$SIGNED_IN" = 1 ]; then
  say "Automatic execution"
  echo "When on, your planned transfers, lineup, captain and chips are submitted 15 minutes before"
  echo "each deadline, after safety checks. You can switch it off any time on the dashboard (Kill switch)."
  ARM=$(ask "Turn automatic execution on now? [y/N] ")
  case "$ARM" in y|Y|yes|YES) "${EXEC[@]}" ingestion-worker python -m app config --auto-execute on ;;
    *) echo "Left off. Plans will still be prepared and sent to you before every deadline." ;; esac
fi

say "Done"
echo "Dashboard:     http://localhost:8000"
echo "API token:     in .env (FPL_API_TOKEN), needed for the dashboard's on/off switch"
echo "Status:        docker compose exec ingestion-worker python -m app auth status"
echo "Kill switch:   docker compose exec ingestion-worker python -m app config --auto-execute off"
echo "Keep Docker Desktop set to start when you log in, and keep this computer awake around deadlines."
